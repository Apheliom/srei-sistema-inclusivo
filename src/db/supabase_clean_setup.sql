-- ====================================================================
-- Script Oficial de Instalación para Supabase (PostgreSQL)
-- Sistema de Registro Estudiantil Inclusivo (SREI)
-- Base de Datos 100% Relacional, Limpia para Producción (0 Estudiantes)
-- ====================================================================

-- 1. Tabla de Instituciones Escolares / Planteles
CREATE TABLE IF NOT EXISTS public.instituciones (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre_institucion VARCHAR(255) NOT NULL UNIQUE,
  codigo_plantel VARCHAR(50),
  ubicacion VARCHAR(255),
  activo SMALLINT NOT NULL DEFAULT 1,
  created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_supabase_instituciones_nombre ON public.instituciones(nombre_institucion);

-- 2. Tabla de Condiciones Diagnósticas Dinámicas
CREATE TABLE IF NOT EXISTS public.condiciones_diagnosticas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre_condicion VARCHAR(150) NOT NULL UNIQUE,
  activo SMALLINT NOT NULL DEFAULT 1
);

-- 3. Tabla de Usuarios y Roles (Directora / Docentes)
CREATE TABLE IF NOT EXISTS public.usuarios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(255) NOT NULL UNIQUE,
  nombre_completo VARCHAR(255) NOT NULL,
  password_hash TEXT NOT NULL,
  rol VARCHAR(50) NOT NULL DEFAULT 'profesor' CHECK(rol IN ('admin', 'profesor')),
  estado VARCHAR(50) NOT NULL DEFAULT 'pendiente_verificacion' CHECK(estado IN ('pendiente_verificacion', 'pendiente_aprobacion', 'activo', 'inactivo')),
  codigo_verificacion VARCHAR(10),
  codigo_expira TIMESTAMPTZ,
  email_verificado SMALLINT DEFAULT 0,
  aprobado_por BIGINT REFERENCES public.usuarios(id),
  aprobado_en TIMESTAMPTZ,
  created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_supabase_usuarios_email ON public.usuarios(email);
CREATE INDEX IF NOT EXISTS idx_supabase_usuarios_rol ON public.usuarios(rol);
CREATE INDEX IF NOT EXISTS idx_supabase_usuarios_estado ON public.usuarios(estado);

-- 4. Tabla Principal de Estudiantes (Bloque 1)
CREATE TABLE IF NOT EXISTS public.estudiantes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  institucion_id BIGINT NOT NULL REFERENCES public.instituciones(id),
  numero_orden INT,
  nombres_apellidos VARCHAR(255) NOT NULL,
  cedula_identidad VARCHAR(32) NOT NULL UNIQUE,
  fecha_nacimiento DATE NOT NULL,
  sexo VARCHAR(20) NOT NULL CHECK(sexo IN ('Masculino', 'Femenino')),
  grado_seccion VARCHAR(50) NOT NULL,
  activo SMALLINT NOT NULL DEFAULT 1,
  registrado_por BIGINT REFERENCES public.usuarios(id),
  created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_supabase_estudiantes_cedula ON public.estudiantes(cedula_identidad);
CREATE INDEX IF NOT EXISTS idx_supabase_estudiantes_institucion ON public.estudiantes(institucion_id);
CREATE INDEX IF NOT EXISTS idx_supabase_estudiantes_grado ON public.estudiantes(grado_seccion);

-- 5. Tabla de Expedientes Médicos y Checklist Digital (Bloques 2, 4 y 5)
CREATE TABLE IF NOT EXISTS public.expedientes_medicos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  estudiante_id BIGINT NOT NULL UNIQUE REFERENCES public.estudiantes(id) ON DELETE CASCADE,
  condicion VARCHAR(150) NOT NULL,
  estatus_diagnostico VARCHAR(100) NOT NULL CHECK(estatus_diagnostico IN ('Diagnóstico Médico Verificado', 'En Proceso de Evaluación', 'Posible Proyección / Por Evaluar')),
  observaciones TEXT,
  atencion_psicologica VARCHAR(30) NOT NULL DEFAULT 'No' CHECK(atencion_psicologica IN ('Sí', 'No', 'En proceso')),
  entrevista_social VARCHAR(30) NOT NULL DEFAULT 'Pendiente' CHECK(entrevista_social IN ('Realizada', 'Pendiente')),
  informe_integral VARCHAR(50) NOT NULL DEFAULT 'En proceso' CHECK(informe_integral IN ('Listo', 'En proceso', 'Falta informe psicológico')),
  toma_medicamento VARCHAR(10) NOT NULL DEFAULT 'No',
  medicamento_detalles TEXT,
  updated_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_supabase_expedientes_condicion ON public.expedientes_medicos(condicion);
CREATE INDEX IF NOT EXISTS idx_supabase_expedientes_estatus ON public.expedientes_medicos(estatus_diagnostico);

-- 6. Tabla de Representantes Legales (Bloque 3)
CREATE TABLE IF NOT EXISTS public.representantes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  estudiante_id BIGINT NOT NULL UNIQUE REFERENCES public.estudiantes(id) ON DELETE CASCADE,
  nombre_representante VARCHAR(255) NOT NULL,
  cedula_representante VARCHAR(50),
  telefono VARCHAR(50) NOT NULL,
  parentesco VARCHAR(50) NOT NULL DEFAULT 'Representante Legal'
);
CREATE INDEX IF NOT EXISTS idx_supabase_representantes_telefono ON public.representantes(telefono);

