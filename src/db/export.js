const fs = require('fs');
const path = require('path');
const db = require('./database');

function generateSupabaseSQL() {
  const outputPath = path.join(__dirname, '..', '..', 'supabase_export.sql');

  const escape = (val) => {
    if (val === null || val === undefined) return 'NULL';
    return `'${String(val).replace(/'/g, "''")}'`;
  };

  const header = `-- ====================================================================
-- Script de Migración para Supabase (PostgreSQL) / MySQL
-- Proyecto: SREI (Sistema de Registro Estudiantil Inclusivo)
-- Base de Datos Relacional Normalizada e Indexada (5 Tablas)
-- Generado el: ${new Date().toISOString()}
-- ====================================================================

-- 1. Tabla de Instituciones Educativas
CREATE TABLE IF NOT EXISTS public.instituciones (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre_institucion VARCHAR(255) NOT NULL UNIQUE,
  codigo_plantel VARCHAR(50),
  ubicacion VARCHAR(255),
  created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_supabase_instituciones_nombre ON public.instituciones(nombre_institucion);

-- 2. Tabla de Usuarios y Roles (Director / Docentes)
CREATE TABLE IF NOT EXISTS public.usuarios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(255) NOT NULL UNIQUE,
  nombre_completo VARCHAR(255) NOT NULL,
  password_hash TEXT NOT NULL,
  rol VARCHAR(50) NOT NULL DEFAULT 'profesor' CHECK(rol IN ('admin', 'profesor')),
  estado VARCHAR(50) NOT NULL DEFAULT 'pendiente_verificacion' CHECK(estado IN ('pendiente_verificacion', 'pendiente_aprobacion', 'activo', 'inactivo')),
  codigo_verificacion VARCHAR(10),
  codigo_expira TIMESTAMPTZ,
  email_verificado SMALLINT DEFAULT 0,
  aprobado_por BIGINT REFERENCES public.usuarios(id),
  aprobado_en TIMESTAMPTZ,
  created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_supabase_usuarios_email ON public.usuarios(email);
CREATE INDEX IF NOT EXISTS idx_supabase_usuarios_rol ON public.usuarios(rol);
CREATE INDEX IF NOT EXISTS idx_supabase_usuarios_estado ON public.usuarios(estado);

-- 3. Tabla Principal de Estudiantes (Bloque 1: Identificación Institucional)
CREATE TABLE IF NOT EXISTS public.estudiantes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  institucion_id BIGINT NOT NULL REFERENCES public.instituciones(id),
  numero_orden INT,
  nombres_apellidos VARCHAR(255) NOT NULL,
  cedula_identidad VARCHAR(32) NOT NULL UNIQUE,
  fecha_nacimiento DATE NOT NULL,
  sexo VARCHAR(20) NOT NULL CHECK(sexo IN ('Masculino', 'Femenino')),
  grado_seccion VARCHAR(50) NOT NULL,
  registrado_por BIGINT REFERENCES public.usuarios(id),
  created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_supabase_estudiantes_cedula ON public.estudiantes(cedula_identidad);
CREATE INDEX IF NOT EXISTS idx_supabase_estudiantes_institucion ON public.estudiantes(institucion_id);
CREATE INDEX IF NOT EXISTS idx_supabase_estudiantes_grado ON public.estudiantes(grado_seccion);

-- 4. Tabla de Expedientes Médicos y Checklist Digital (Bloques 2 y 4)
CREATE TABLE IF NOT EXISTS public.expedientes_medicos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  estudiante_id BIGINT NOT NULL UNIQUE REFERENCES public.estudiantes(id) ON DELETE CASCADE,
  condicion VARCHAR(150) NOT NULL,
  estatus_diagnostico VARCHAR(100) NOT NULL CHECK(estatus_diagnostico IN ('Diagnóstico Médico Verificado', 'En Proceso de Evaluación', 'Posible Proyección / Por Evaluar')),
  observaciones TEXT,
  atencion_psicologica VARCHAR(30) NOT NULL DEFAULT 'No' CHECK(atencion_psicologica IN ('Sí', 'No', 'En proceso')),
  entrevista_social VARCHAR(30) NOT NULL DEFAULT 'Pendiente' CHECK(entrevista_social IN ('Realizada', 'Pendiente')),
  informe_integral VARCHAR(50) NOT NULL DEFAULT 'En proceso' CHECK(informe_integral IN ('Listo', 'En proceso', 'Falta informe psicológico')),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_supabase_expedientes_condicion ON public.expedientes_medicos(condicion);
CREATE INDEX IF NOT EXISTS idx_supabase_expedientes_estatus ON public.expedientes_medicos(estatus_diagnostico);

-- 5. Tabla de Representantes Legales (Bloque 3)
CREATE TABLE IF NOT EXISTS public.representantes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  estudiante_id BIGINT NOT NULL UNIQUE REFERENCES public.estudiantes(id) ON DELETE CASCADE,
  nombre_representante VARCHAR(255) NOT NULL,
  cedula_representante VARCHAR(50),
  telefono VARCHAR(50) NOT NULL,
  parentesco VARCHAR(50) NOT NULL DEFAULT 'Representante Legal'
);
CREATE INDEX IF NOT EXISTS idx_supabase_representantes_telefono ON public.representantes(telefono);

-- Habilitar Row Level Security (RLS)
ALTER TABLE public.instituciones ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.usuarios ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.estudiantes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.expedientes_medicos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.representantes ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Lectura libre SREI" ON public.instituciones FOR SELECT USING (true);
CREATE POLICY "Lectura usuarios SREI" ON public.usuarios FOR SELECT USING (true);
CREATE POLICY "Lectura estudiantes SREI" ON public.estudiantes FOR SELECT USING (true);
CREATE POLICY "Lectura expedientes SREI" ON public.expedientes_medicos FOR SELECT USING (true);
CREATE POLICY "Lectura representantes SREI" ON public.representantes FOR SELECT USING (true);
`;

  // Datos Instituciones
  const instituciones = db.prepare('SELECT * FROM instituciones ORDER BY id ASC').all();
  let sqlInst = '\n-- Volcado: instituciones\n';
  sqlInst += instituciones.map(i => `INSERT INTO public.instituciones (id, nombre_institucion, codigo_plantel, ubicacion) OVERRIDING SYSTEM VALUE VALUES (${i.id}, ${escape(i.nombre_institucion)}, ${escape(i.codigo_plantel)}, ${escape(i.ubicacion)}) ON CONFLICT (nombre_institucion) DO NOTHING;`).join('\n') + '\n';

  // Datos Usuarios
  const usuarios = db.prepare('SELECT * FROM usuarios ORDER BY id ASC').all();
  let sqlUsr = '\n-- Volcado: usuarios\n';
  sqlUsr += usuarios.map(u => `INSERT INTO public.usuarios (id, email, nombre_completo, password_hash, rol, estado, email_verificado) OVERRIDING SYSTEM VALUE VALUES (${u.id}, ${escape(u.email)}, ${escape(u.nombre_completo)}, ${escape(u.password_hash)}, ${escape(u.rol)}, ${escape(u.estado)}, ${u.email_verificado}) ON CONFLICT (email) DO NOTHING;`).join('\n') + '\n';

  // Datos Estudiantes
  const estudiantes = db.prepare('SELECT * FROM estudiantes ORDER BY id ASC').all();
  let sqlEst = '\n-- Volcado: estudiantes\n';
  sqlEst += estudiantes.map(e => `INSERT INTO public.estudiantes (id, institucion_id, numero_orden, nombres_apellidos, cedula_identidad, fecha_nacimiento, sexo, grado_seccion, registrado_por) OVERRIDING SYSTEM VALUE VALUES (${e.id}, ${e.institucion_id}, ${e.numero_orden || 'NULL'}, ${escape(e.nombres_apellidos)}, ${escape(e.cedula_identidad)}, ${escape(e.fecha_nacimiento)}, ${escape(e.sexo)}, ${escape(e.grado_seccion)}, ${e.registrado_por || 'NULL'}) ON CONFLICT (cedula_identidad) DO NOTHING;`).join('\n') + '\n';

  // Datos Expedientes Médicos
  const expMedicos = db.prepare('SELECT * FROM expedientes_medicos ORDER BY id ASC').all();
  let sqlMed = '\n-- Volcado: expedientes_medicos\n';
  sqlMed += expMedicos.map(m => `INSERT INTO public.expedientes_medicos (id, estudiante_id, condicion, estatus_diagnostico, observaciones, atencion_psicologica, entrevista_social, informe_integral) OVERRIDING SYSTEM VALUE VALUES (${m.id}, ${m.estudiante_id}, ${escape(m.condicion)}, ${escape(m.estatus_diagnostico)}, ${escape(m.observaciones)}, ${escape(m.atencion_psicologica)}, ${escape(m.entrevista_social)}, ${escape(m.informe_integral)}) ON CONFLICT (estudiante_id) DO NOTHING;`).join('\n') + '\n';

  // Datos Representantes
  const reps = db.prepare('SELECT * FROM representantes ORDER BY id ASC').all();
  let sqlRep = '\n-- Volcado: representantes\n';
  sqlRep += reps.map(r => `INSERT INTO public.representantes (id, estudiante_id, nombre_representante, cedula_representante, telefono, parentesco) OVERRIDING SYSTEM VALUE VALUES (${r.id}, ${r.estudiante_id}, ${escape(r.nombre_representante)}, ${escape(r.cedula_representante)}, ${escape(r.telefono)}, ${escape(r.parentesco)}) ON CONFLICT (estudiante_id) DO NOTHING;`).join('\n') + '\n';

  const fullSQL = header + sqlInst + sqlUsr + sqlEst + sqlMed + sqlRep;
  fs.writeFileSync(outputPath, fullSQL, 'utf8');
  console.log(`[SQL Export] Exportación relacional completa generada en: ${outputPath}`);
  return { outputPath, instituciones: instituciones.length, usuarios: usuarios.length, estudiantes: estudiantes.length };
}

if (require.main === module) {
  generateSupabaseSQL();
}

module.exports = { generateSupabaseSQL };
