const fs = require('fs');
const path = require('path');
const db = require('./database');

function generateSupabaseSQL() {
  const outputPath = path.join(__dirname, '..', '..', 'supabase_export.sql');

  const escape = (val) => {
    if (val === null || val === undefined) return 'NULL';
    if (typeof val === 'number') return val;
    return `'${String(val).replace(/'/g, "''")}'`;
  };

  const header = `-- ====================================================================
-- Script de Respaldo y Migración Oficial para Supabase (PostgreSQL) / SREI
-- Proyecto: SREI (Sistema de Registro Estudiantil Inclusivo)
-- Base de Datos Relacional Completa con 7 Tablas y Registro Vivo Actual
-- Generado el: ${new Date().toISOString()}
-- ====================================================================

-- 1. Tabla de Instituciones Educativas
CREATE TABLE IF NOT EXISTS public.instituciones (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre_institucion VARCHAR(255) NOT NULL UNIQUE,
  codigo_plantel VARCHAR(50),
  ubicacion VARCHAR(255),
  activo SMALLINT NOT NULL DEFAULT 1,
  created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_supabase_instituciones_nombre ON public.instituciones(nombre_institucion);

-- 2. Tabla de Condiciones Diagnósticas Normalizadas
CREATE TABLE IF NOT EXISTS public.condiciones_diagnosticas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(255) NOT NULL UNIQUE,
  categoria VARCHAR(100) DEFAULT 'General',
  activo SMALLINT NOT NULL DEFAULT 1,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Tabla de Usuarios y Roles (Director / Docentes)
CREATE TABLE IF NOT EXISTS public.usuarios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(255) NOT NULL UNIQUE,
  nombre_completo VARCHAR(255) NOT NULL,
  password_hash TEXT NOT NULL,
  rol VARCHAR(50) NOT NULL DEFAULT 'profesor' CHECK(rol IN ('admin', 'profesor')),
  estado VARCHAR(50) NOT NULL DEFAULT 'pendiente_verificacion' CHECK(estado IN ('pendiente_verificacion', 'pendiente_aprobacion', 'activo', 'inactivo')),
  codigo_verificacion VARCHAR(10),
  codigo_expira TIMESTAMPTZ,
  email_verificado SMALLINT DEFAULT 0,
  aprobado_por BIGINT REFERENCES public.usuarios(id),
  aprobado_en TIMESTAMPTZ,
  created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_supabase_usuarios_email ON public.usuarios(email);
CREATE INDEX IF NOT EXISTS idx_supabase_usuarios_rol ON public.usuarios(rol);
CREATE INDEX IF NOT EXISTS idx_supabase_usuarios_estado ON public.usuarios(estado);

-- 4. Tabla Principal de Estudiantes (Identificación y Asignación Docente)
CREATE TABLE IF NOT EXISTS public.estudiantes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  institucion_id BIGINT NOT NULL REFERENCES public.instituciones(id),
  numero_orden INT,
  nombres_apellidos VARCHAR(255) NOT NULL,
  cedula_identidad VARCHAR(32) NOT NULL UNIQUE,
  fecha_nacimiento DATE NOT NULL,
  sexo VARCHAR(20) NOT NULL CHECK(sexo IN ('Masculino', 'Femenino')),
  grado_seccion VARCHAR(50) NOT NULL,
  activo SMALLINT NOT NULL DEFAULT 1,
  registrado_por BIGINT REFERENCES public.usuarios(id),
  docente_id BIGINT REFERENCES public.usuarios(id),
  created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_supabase_estudiantes_cedula ON public.estudiantes(cedula_identidad);
CREATE INDEX IF NOT EXISTS idx_supabase_estudiantes_institucion ON public.estudiantes(institucion_id);
CREATE INDEX IF NOT EXISTS idx_supabase_estudiantes_grado ON public.estudiantes(grado_seccion);
CREATE INDEX IF NOT EXISTS idx_supabase_estudiantes_docente ON public.estudiantes(docente_id);

-- 5. Tabla de Expedientes Médicos y Checklist Digital (Bloques 2 y 4)
CREATE TABLE IF NOT EXISTS public.expedientes_medicos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  estudiante_id BIGINT NOT NULL UNIQUE REFERENCES public.estudiantes(id) ON DELETE CASCADE,
  condicion VARCHAR(150) NOT NULL,
  estatus_diagnostico VARCHAR(100) NOT NULL CHECK(estatus_diagnostico IN ('Diagnóstico Médico Verificado', 'En Proceso de Evaluación', 'Posible Proyección / Por Evaluar')),
  observaciones TEXT,
  atencion_psicologica VARCHAR(30) NOT NULL DEFAULT 'No' CHECK(atencion_psicologica IN ('Sí', 'No', 'En proceso')),
  entrevista_social VARCHAR(30) NOT NULL DEFAULT 'Pendiente' CHECK(entrevista_social IN ('Realizada', 'Pendiente')),
  informe_integral VARCHAR(50) NOT NULL DEFAULT 'En proceso' CHECK(informe_integral IN ('Listo', 'En proceso', 'Falta informe psicológico')),
  toma_medicamento VARCHAR(10) NOT NULL DEFAULT 'No',
  medicamento_detalles TEXT,
  updated_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_supabase_expedientes_condicion ON public.expedientes_medicos(condicion);
CREATE INDEX IF NOT EXISTS idx_supabase_expedientes_estatus ON public.expedientes_medicos(estatus_diagnostico);

-- 6. Tabla de Representantes Legales (Bloque 3)
CREATE TABLE IF NOT EXISTS public.representantes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  estudiante_id BIGINT NOT NULL UNIQUE REFERENCES public.estudiantes(id) ON DELETE CASCADE,
  nombre_representante VARCHAR(255) NOT NULL,
  cedula_representante VARCHAR(50),
  telefono VARCHAR(50) NOT NULL,
  parentesco VARCHAR(50) NOT NULL DEFAULT 'Representante Legal'
);
CREATE INDEX IF NOT EXISTS idx_supabase_representantes_telefono ON public.representantes(telefono);

-- 7. Tabla Institucional de Auditoría y Bitácora
CREATE TABLE IF NOT EXISTS public.bitacora (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id BIGINT,
  usuario_nombre VARCHAR(255),
  usuario_email VARCHAR(255),
  usuario_rol VARCHAR(50),
  accion VARCHAR(100) NOT NULL,
  modulo VARCHAR(100) NOT NULL,
  detalles TEXT NOT NULL,
  ip_address VARCHAR(100),
  created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_supabase_bitacora_created ON public.bitacora(created_at);
CREATE INDEX IF NOT EXISTS idx_supabase_bitacora_modulo ON public.bitacora(modulo);

-- Habilitar Row Level Security (RLS)
ALTER TABLE public.instituciones ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.condiciones_diagnosticas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.usuarios ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.estudiantes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.expedientes_medicos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.representantes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.bitacora ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Lectura libre instituciones" ON public.instituciones FOR SELECT USING (true);
CREATE POLICY "Lectura libre condiciones" ON public.condiciones_diagnosticas FOR SELECT USING (true);
CREATE POLICY "Lectura libre usuarios" ON public.usuarios FOR SELECT USING (true);
CREATE POLICY "Lectura libre estudiantes" ON public.estudiantes FOR SELECT USING (true);
CREATE POLICY "Lectura libre expedientes" ON public.expedientes_medicos FOR SELECT USING (true);
CREATE POLICY "Lectura libre representantes" ON public.representantes FOR SELECT USING (true);
CREATE POLICY "Lectura libre bitacora" ON public.bitacora FOR SELECT USING (true);
`;

  // 1. Datos Instituciones
  const instituciones = db.prepare('SELECT * FROM instituciones ORDER BY id ASC').all();
  let sqlInst = '\n-- Volcado Actual: instituciones\n';
  sqlInst += instituciones.map(i => `INSERT INTO public.instituciones (id, nombre_institucion, codigo_plantel, ubicacion, activo) OVERRIDING SYSTEM VALUE VALUES (${i.id}, ${escape(i.nombre_institucion)}, ${escape(i.codigo_plantel)}, ${escape(i.ubicacion)}, ${i.activo ?? 1}) ON CONFLICT (id) DO UPDATE SET nombre_institucion = EXCLUDED.nombre_institucion, codigo_plantel = EXCLUDED.codigo_plantel, ubicacion = EXCLUDED.ubicacion, activo = EXCLUDED.activo;`).join('\n') + '\n';

  // 2. Datos Condiciones Diagnósticas
  let sqlCond = '\n-- Volcado Actual: condiciones_diagnosticas\n';
  try {
    const condiciones = db.prepare('SELECT * FROM condiciones_diagnosticas ORDER BY id ASC').all();
    sqlCond += condiciones.map(c => `INSERT INTO public.condiciones_diagnosticas (id, nombre, categoria, activo) OVERRIDING SYSTEM VALUE VALUES (${c.id}, ${escape(c.nombre || c.nombre_condicion)}, ${escape(c.categoria || 'General')}, ${c.activo ?? 1}) ON CONFLICT (id) DO NOTHING;`).join('\n') + '\n';
  } catch (e) {}

  // 3. Datos Usuarios
  const usuarios = db.prepare('SELECT * FROM usuarios ORDER BY id ASC').all();
  let sqlUsr = '\n-- Volcado Actual: usuarios\n';
  sqlUsr += usuarios.map(u => `INSERT INTO public.usuarios (id, email, nombre_completo, password_hash, rol, estado, email_verificado) OVERRIDING SYSTEM VALUE VALUES (${u.id}, ${escape(u.email)}, ${escape(u.nombre_completo)}, ${escape(u.password_hash)}, ${escape(u.rol)}, ${escape(u.estado)}, ${u.email_verificado ?? 0}) ON CONFLICT (id) DO UPDATE SET nombre_completo = EXCLUDED.nombre_completo, password_hash = EXCLUDED.password_hash, rol = EXCLUDED.rol, estado = EXCLUDED.estado, email_verificado = EXCLUDED.email_verificado;`).join('\n') + '\n';

  // 4. Datos Estudiantes
  const estudiantes = db.prepare('SELECT * FROM estudiantes ORDER BY id ASC').all();
  let sqlEst = '\n-- Volcado Actual: estudiantes\n';
  sqlEst += estudiantes.map(e => `INSERT INTO public.estudiantes (id, institucion_id, numero_orden, nombres_apellidos, cedula_identidad, fecha_nacimiento, sexo, grado_seccion, activo, registrado_por, docente_id) OVERRIDING SYSTEM VALUE VALUES (${e.id}, ${e.institucion_id}, ${e.numero_orden || 'NULL'}, ${escape(e.nombres_apellidos)}, ${escape(e.cedula_identidad)}, ${escape(e.fecha_nacimiento)}, ${escape(e.sexo)}, ${escape(e.grado_seccion)}, ${e.activo ?? 1}, ${e.registrado_por || 'NULL'}, ${e.docente_id || 'NULL'}) ON CONFLICT (id) DO UPDATE SET nombres_apellidos = EXCLUDED.nombres_apellidos, cedula_identidad = EXCLUDED.cedula_identidad, fecha_nacimiento = EXCLUDED.fecha_nacimiento, sexo = EXCLUDED.sexo, grado_seccion = EXCLUDED.grado_seccion, activo = EXCLUDED.activo, docente_id = EXCLUDED.docente_id;`).join('\n') + '\n';

  // 5. Datos Expedientes Médicos
  const expMedicos = db.prepare('SELECT * FROM expedientes_medicos ORDER BY id ASC').all();
  let sqlMed = '\n-- Volcado Actual: expedientes_medicos\n';
  sqlMed += expMedicos.map(m => `INSERT INTO public.expedientes_medicos (id, estudiante_id, condicion, estatus_diagnostico, observaciones, atencion_psicologica, entrevista_social, informe_integral, toma_medicamento, medicamento_detalles) OVERRIDING SYSTEM VALUE VALUES (${m.id}, ${m.estudiante_id}, ${escape(m.condicion)}, ${escape(m.estatus_diagnostico)}, ${escape(m.observaciones)}, ${escape(m.atencion_psicologica)}, ${escape(m.entrevista_social)}, ${escape(m.informe_integral)}, ${escape(m.toma_medicamento || 'No')}, ${escape(m.medicamento_detalles || '')}) ON CONFLICT (estudiante_id) DO UPDATE SET condicion = EXCLUDED.condicion, estatus_diagnostico = EXCLUDED.estatus_diagnostico, observaciones = EXCLUDED.observaciones, atencion_psicologica = EXCLUDED.atencion_psicologica, entrevista_social = EXCLUDED.entrevista_social, informe_integral = EXCLUDED.informe_integral, toma_medicamento = EXCLUDED.toma_medicamento, medicamento_detalles = EXCLUDED.medicamento_detalles;`).join('\n') + '\n';

  // 6. Datos Representantes
  const reps = db.prepare('SELECT * FROM representantes ORDER BY id ASC').all();
  let sqlRep = '\n-- Volcado Actual: representantes\n';
  sqlRep += reps.map(r => `INSERT INTO public.representantes (id, estudiante_id, nombre_representante, cedula_representante, telefono, parentesco) OVERRIDING SYSTEM VALUE VALUES (${r.id}, ${r.estudiante_id}, ${escape(r.nombre_representante)}, ${escape(r.cedula_representante)}, ${escape(r.telefono)}, ${escape(r.parentesco)}) ON CONFLICT (estudiante_id) DO UPDATE SET nombre_representante = EXCLUDED.nombre_representante, cedula_representante = EXCLUDED.cedula_representante, telefono = EXCLUDED.telefono, parentesco = EXCLUDED.parentesco;`).join('\n') + '\n';

  // 7. Datos Bitácora
  let sqlBit = '\n-- Volcado Actual: bitacora\n';
  try {
    const logs = db.prepare('SELECT * FROM bitacora ORDER BY id ASC LIMIT 500').all();
    sqlBit += logs.map(b => `INSERT INTO public.bitacora (id, usuario_id, usuario_nombre, usuario_email, usuario_rol, accion, modulo, detalles, ip_address, created_at) OVERRIDING SYSTEM VALUE VALUES (${b.id}, ${b.usuario_id || 'NULL'}, ${escape(b.usuario_nombre)}, ${escape(b.usuario_email)}, ${escape(b.usuario_rol)}, ${escape(b.accion)}, ${escape(b.modulo)}, ${escape(b.detalles)}, ${escape(b.ip_address)}, ${escape(b.created_at)}) ON CONFLICT (id) DO NOTHING;`).join('\n') + '\n';
  } catch (e) {}

  const fullSQL = header + sqlInst + sqlCond + sqlUsr + sqlEst + sqlMed + sqlRep + sqlBit;
  fs.writeFileSync(outputPath, fullSQL, 'utf8');
  console.log(`[SQL Export] Exportación relacional viva completa generada en: ${outputPath}`);
  return { outputPath, instituciones: instituciones.length, usuarios: usuarios.length, estudiantes: estudiantes.length };
}

if (require.main === module) {
  generateSupabaseSQL();
}

module.exports = { generateSupabaseSQL };
